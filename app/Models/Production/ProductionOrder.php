<?php

namespace App\Models\Production;

use App\Models\Concerns\HasAuditLabel;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;

/**
 * Orden de Producción.
 *
 * Aggregate Root del dominio de producción. Representa una orden para producir
 * unidades de un producto (ProductSheet). Contiene una TechnicalSheet que
 * agrega operaciones, materiales, procesos y costos.
 *
 * Flujo: DiseñoProducto → ProductionOrder → TechnicalSheet → (Operaciones, Materiales, Costos)
 *
 * @property int $id
 * @property int $product_sheet_id
 * @property string|null $op_code
 * @property string $season
 * @property int $destination_id
 * @property string|null $priority
 * @property int|null $units
 * @property \Carbon\Carbon|null $estimated_delivery_date
 * @property array|null $ecommerce_units
 * @property string $status
 * @property string $current_process
 * @property string $source
 *
 * @see \App\Services\Production\ProductionOrderService
 */
class ProductionOrder extends Model
{
    use HasFactory, SoftDeletes, HasAuditLabel;

    protected $table = 'production_orders';

    protected $fillable = [
        'product_sheet_id',
        'op_code',
        'season',
        'season_month',
        'season_year',
        'dispatch_month',
        'dispatch_month_num',
        'dispatch_year',
        'destination_id',
        'priority',
        'units',
        'estimated_delivery_date',
        'is_advance',
        'notes',
        'ecommerce_units',
        'status',
        'current_process',
        'batch_priority',
        'process_estimated_dates',
        'cut_fabric_consumption',
        'source',
        'created_by_user_id',
        'billing_price_override',
        'selling_price_override',
        'calculated_cost',
    ];

    protected $casts = [
        'ecommerce_units'          => 'array',
        'estimated_delivery_date'  => 'date',
        'is_advance'               => 'boolean',
        'process_estimated_dates'  => 'array',
        'cut_fabric_consumption'    => 'array',
        'batch_priority'            => 'integer',
        'billing_price_override'    => 'float',
        'selling_price_override'    => 'float',
        'calculated_cost'           => 'float',
        'created_by_user_id'       => 'integer',
        // Columnas canónicas Fase A
        'season_month'             => 'integer',
        'season_year'              => 'integer',
        'dispatch_month_num'       => 'integer',
        'dispatch_year'            => 'integer',
    ];

    protected $appends = [
        'is_auto_from_product_sheet',
    ];

    // ─── Accessors ────────────────────────────────────────

    public function getIsAutoFromProductSheetAttribute(): bool
    {
        return $this->source === 'auto';
    }

    // ─── Helpers de dominio ───────────────────────────────

    public function isAutoGenerated(): bool
    {
        return $this->source === 'auto';
    }

    public function isManual(): bool
    {
        return $this->source === 'manual';
    }

    /**
     * Construye la referencia de display combinando sample_reference y product_reference.
     */
    public function getDisplayReference(): string
    {
        $sheetType = strtolower(trim((string) ($this->productSheet?->type ?? '')));
        $sampleRef  = trim($this->productSheet?->sample_reference ?? '');
        $productRef = trim($this->productSheet?->product_reference ?? '');

        if ($sheetType === 'muestra' && $sampleRef !== '') {
            return $sampleRef;
        }

        if ($sheetType === 'producto' && $productRef !== '') {
            return $productRef;
        }

        if ($sampleRef && $productRef) {
            return $sampleRef === $productRef ? $sampleRef : "{$sampleRef} - {$productRef}";
        }

        return $sampleRef ?: ($productRef ?: 'Sin referencia');
    }

    /**
     * Extrae el tipo de OP canónico (MU|MF) del código de la orden.
     * Compatibilidad legacy: MUT => MU, MFT => MF.
     */
    public function getOpType(): string
    {
        $code = strtoupper(trim($this->op_code ?? ''));

        if (str_starts_with($code, 'MUT')) return 'MU';
        if (str_starts_with($code, 'MU'))  return 'MU';
        if (str_starts_with($code, 'MFT')) return 'MF';

        return 'MF';
    }

    // ─── Relaciones ───────────────────────────────────────

    public function creator()
    {
        return $this->belongsTo(\App\Models\Settings\User::class, 'created_by_user_id');
    }

    /**
     * Sábana de producto (diseño/producto base).
     */
    public function productSheet()
    {
        return $this->belongsTo(ProductSheet::class);
    }

    /**
     * Ficha técnica asociada (Aggregate de operaciones, costos, materiales).
     */
    public function technicalSheet()
    {
        return $this->hasOne(\App\Models\Production\TechnicalSheet::class);
    }

    /**
     * Acceso directo a operaciones de la ficha técnica.
     */
    public function technicalSheetOperations()
    {
        return $this->hasManyThrough(
            \App\Models\Production\TechnicalSheetOperation::class,
            \App\Models\Production\TechnicalSheet::class,
            'production_order_id', // FK en technical_sheets
            'technical_sheet_id',  // FK en technical_sheet_operations
            'id',                  // PK en production_orders
            'id'                   // PK en technical_sheets
        );
    }

    public function rollConsumptions()
    {
        return $this->hasMany(ProductionRollConsumption::class);
    }

    /**
     * Historial de entregas del control de lotes.
     */
    public function batchDeliveries()
    {
        return $this->hasMany(BatchControlDelivery::class);
    }

    /**
     * Última entrega registrada.
     */
    public function lastDelivery()
    {
        return $this->hasOne(BatchControlDelivery::class)->latestOfMany();
    }

    /**
     * Novedades/devoluciones del control de lotes.
     */
    public function batchNovelties()
    {
        return $this->hasMany(BatchControlNovelty::class);
    }

    /**
     * Novedades pendientes (no resueltas).
     */
    public function pendingNovelties()
    {
        return $this->hasMany(BatchControlNovelty::class)->where('status', 'pending');
    }

    public function warehouseReceipt()
    {
        return $this->hasOne(\App\Models\Production\BatchControlWarehouseReceipt::class);
    }

    // ─── Batch Control Setters ──────────────────────────

    /**
     * Actualiza la prioridad de lote.
     * Método controlado para BatchControl.
     */
    public function updateBatchPriority(int $priority): self
    {
        $this->setAttribute('batch_priority', $priority);
        return $this;
    }

    /**
     * Actualiza las fechas estimadas de procesos.
     * Método controlado para BatchControl.
     */
    public function updateProcessEstimatedDates(array $dates): self
    {
        $this->setAttribute('process_estimated_dates', $dates);
        return $this;
    }
}
