<?php

namespace App\Models\ProductSheet;

use App\Models\Concerns\HasAuditLabel;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;

/**
 * Orden de producción (Programmer en código, ProductionOrder en documentación).
 *
 * Representa una orden para producir unidades de un producto (ProductSheet).
 * Al crearse, genera un snapshot congelado de operaciones (ProductionOrderOperation).
 *
 * @see \App\Services\ProductSheet\ProductionOrderService
 */
class Programmer extends Model
{
    use HasFactory, SoftDeletes, HasAuditLabel;

    protected $table = 'programmers';

    protected $fillable = [
        'product_sheet_id',
        'op_code',
        'season',
        'destination_id',
        'priority',
        'units',
        'estimated_delivery_date',
        'ecommerce_units',
        'status',
        'current_process',
        'source',
    ];

    protected $casts = [
        'ecommerce_units' => 'array',
        'estimated_delivery_date' => 'date',
    ];

    protected $appends = [
        'is_auto_from_product_sheet',
    ];

    public function getIsAutoFromProductSheetAttribute(): bool
    {
        return $this->source === 'auto';
    }

    public function isAutoGenerated(): bool
    {
        return $this->source === 'auto';
    }

    public function isManual(): bool
    {
        return $this->source === 'manual';
    }

    public function productSheet()
    {
        return $this->belongsTo(ProductSheet::class);
    }

    public function productionOrderOperations()
    {
        return $this->hasMany(ProductionOrderOperation::class, 'programmer_id');
    }

    /**
     * Acceso directo a las máquinas usadas en las operaciones de esta orden.
     */
    public function machines()
    {
        return $this->hasManyThrough(
            Machine::class,
            ProductionOrderOperation::class,
            'programmer_id',
            'id',
            'id',
            'machine_id'
        );
    }
}
