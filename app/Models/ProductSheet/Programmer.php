<?php

namespace App\Models\ProductSheet;

use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;

class Programmer extends Model
{
    use HasFactory, SoftDeletes;

    protected $table = 'programmers';

    protected $fillable = [
        'product_sheet_id',
        'op_code',
        'season',
        'destination_id',
        'priority',
        'units',
        'estimated_delivery_date',
        'ecommerce_units',
        'status',
        'source',
    ];

    protected $casts = [
        'ecommerce_units' => 'array',
        'estimated_delivery_date' => 'date',
    ];

    /**
     * Atributos a incluir automáticamente en la serialización JSON.
     */
    protected $appends = [
        'is_auto_from_product_sheet',
    ];

    /**
     * Accessor: Indica si el registro fue auto-generado desde Sábana de Productos.
     * Se basa en el campo `source` que se setea al crear el registro.
     * 
     * @return bool
     */
    public function getIsAutoFromProductSheetAttribute(): bool
    {
        return $this->source === 'auto';
    }

    /**
     * Indica si el registro fue auto-generado desde Sábana de Productos.
     */
    public function isAutoGenerated(): bool
    {
        return $this->source === 'auto';
    }

    /**
     * Indica si el registro fue creado manualmente desde el módulo Programador.
     */
    public function isManual(): bool
    {
        return $this->source === 'manual';
    }

    public function productSheet()
    {
        return $this->belongsTo(ProductSheet::class);
    }
}
