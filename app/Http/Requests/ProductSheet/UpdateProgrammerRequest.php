<?php

namespace App\Http\Requests\ProductSheet;

use App\Models\Production\ProductionOrder;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Contracts\Validation\Validator;
use Illuminate\Http\Exceptions\HttpResponseException;
use Illuminate\Validation\Rule;

/**
 * FormRequest para actualizar un Programador existente.
 * 
 * Reglas según tipo de registro:
 * - Auto (OP empieza con "MF"): priority ignorado, estimated_delivery_date permitido
 * - Manual (OP empieza con "MU"): priority requerido, estimated_delivery_date ignorado
 */
class UpdateProgrammerRequest extends FormRequest
{
    private const PRIORITIES = ['A', 'B', 'C', 'D'];
    private const STATUSES = ['complete', 'incomplete'];

    private ?ProductionOrder $programmerModel = null;

    public function authorize(): bool
    {
        return true;
    }

    /**
     * Obtiene el modelo ProductionOrder de la ruta.
     */
    protected function getProgrammer(): ?ProductionOrder
    {
        if ($this->programmerModel === null) {
            $routeParam = $this->route('programador');

            if ($routeParam instanceof ProductionOrder) {
                $this->programmerModel = $routeParam;
            } elseif (is_numeric($routeParam) || is_string($routeParam)) {
                $this->programmerModel = ProductionOrder::find($routeParam);
            } else {
                $this->programmerModel = null;
            }
        }

        return $this->programmerModel;
    }

    /**
     * Determina si el registro es auto-generado usando el método del modelo.
     */
    protected function isAutoGenerated(): bool
    {
        $programmer = $this->getProgrammer();

        return $programmer?->isAutoGenerated() ?? false;
    }

    /**
     * Limpia campos según el tipo de registro antes de validar.
     */
    protected function prepareForValidation(): void
    {
        $isAuto = $this->isAutoGenerated();

        if ($isAuto) {
            // Auto-generados: forzar priority a null (no aplica)
            $this->merge([
                'priority' => null,
            ]);
        } else {
            // Manuales: forzar estimated_delivery_date a null (no aplica)
            $this->merge([
                'estimated_delivery_date' => null,
            ]);
        }
    }

    public function rules(): array
    {
        return [
            'product_sheet_id' => 'sometimes|exists:product_sheets,id',
            'season' => 'sometimes|string|max:255',
            'destination_id' => 'sometimes|integer|min:1',
            
            // Priority: requerido solo para manuales, ignorado para auto
            'priority' => [
                'sometimes',
                'nullable',
                'string',
                Rule::in(self::PRIORITIES),
            ],

            'units' => 'sometimes|nullable|integer|min:1',

            // Estimated delivery date: permitido para auto, ignorado para manual
            'estimated_delivery_date' => [
                'sometimes',
                'nullable',
                'date',
            ],

            'ecommerce_units' => 'sometimes|nullable',
            'status' => ['sometimes', 'string', Rule::in(self::STATUSES)],
        ];
    }

    public function messages(): array
    {
        return [
            'priority.in' => 'La prioridad debe ser A, B, C o D.',
            'destination_id.required' => 'El destino es obligatorio.',
            'destination_id.integer' => 'El destino debe ser un número válido.',
            'season.required' => 'La temporada es obligatoria.',
            'units.integer' => 'Las unidades deben ser un número entero.',
            'units.min' => 'Las unidades deben ser al menos 1.',
            'estimated_delivery_date.date' => 'La fecha de entrega estimada debe ser una fecha válida.',
            'status.in' => 'El estado debe ser "complete" o "incomplete".',
        ];
    }

    /**
     * Maneja errores de validación retornando JSON.
     */
    protected function failedValidation(Validator $validator): void
    {
        throw new HttpResponseException(response()->json([
            'message' => 'Error de validación.',
            'errors' => $validator->errors(),
        ], 422));
    }

    /**
     * Obtiene los datos validados con campos limpiados según tipo.
     */
    public function validatedWithCleanup(): array
    {
        $validated = $this->validated();
        $isAuto = $this->isAutoGenerated();

        if ($isAuto) {
            // Auto-generados: asegurar que priority no se envíe
            unset($validated['priority']);
        } else {
            // Manuales: asegurar que estimated_delivery_date no se envíe
            unset($validated['estimated_delivery_date']);
        }

        return $validated;
    }
}
