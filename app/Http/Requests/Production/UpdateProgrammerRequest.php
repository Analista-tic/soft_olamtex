<?php

namespace App\Http\Requests\Production;

use App\Models\Production\Programmer;
use Illuminate\Contracts\Validation\Validator;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Http\Exceptions\HttpResponseException;
use Illuminate\Validation\Rule;

class UpdateProgrammerRequest extends FormRequest
{
    private const PRIORITIES = ['A', 'B', 'C', 'D'];
    private const STATUSES = ['complete', 'incomplete'];

    private ?Programmer $programmerModel = null;

    public function authorize(): bool
    {
        return true;
    }

    protected function getProgrammer(): ?Programmer
    {
        if ($this->programmerModel !== null) {
            return $this->programmerModel;
        }

        $routeParam = $this->route('programador');

        if ($routeParam instanceof Programmer) {
            $this->programmerModel = $routeParam;
        } elseif (is_numeric($routeParam) || is_string($routeParam)) {
            $this->programmerModel = Programmer::find($routeParam);
        }

        return $this->programmerModel;
    }

    protected function isAutoGenerated(): bool
    {
        return $this->getProgrammer()?->isAutoGenerated() ?? false;
    }

    protected function prepareForValidation(): void
    {
        if ($this->isAutoGenerated()) {
            $this->merge(['priority' => null]);
            return;
        }

        $this->merge(['estimated_delivery_date' => null]);
    }

    public function rules(): array
    {
        $isAuto = $this->isAutoGenerated();

        return [
            'product_sheet_id' => ['sometimes', 'exists:product_sheets,id'],
            'season' => ['sometimes', 'string', 'max:255'],
            'destination_id' => ['sometimes', 'integer', 'min:1'],
            'priority' => [
                'sometimes',
                'nullable',
                'string',
                Rule::in(self::PRIORITIES),
                Rule::requiredIf(fn () => !$isAuto && $this->has('priority')),
            ],
            'units' => ['sometimes', 'nullable', 'integer', 'min:1'],
            'estimated_delivery_date' => ['sometimes', 'nullable', 'date'],
            'ecommerce_units' => ['sometimes', 'nullable'],
            'status' => ['sometimes', 'string', Rule::in(self::STATUSES)],
        ];
    }

    protected function failedValidation(Validator $validator): void
    {
        throw new HttpResponseException(response()->json([
            'message' => 'Error de validacion.',
            'errors' => $validator->errors(),
        ], 422));
    }

    public function validatedWithCleanup(): array
    {
        $validated = $this->validated();

        if ($this->isAutoGenerated()) {
            unset($validated['priority']);
            return $validated;
        }

        unset($validated['estimated_delivery_date']);
        return $validated;
    }
}
