<script setup lang="ts">
import FormDialogContent from '@/components/FormDialogContent.vue';
import HelpTooltip from '@/components/HelpTooltip.vue';
import InputField from '@/components/InputField.vue';
import SelectField from '@/components/SelectField.vue';
import { Button } from '@/components/ui/button';
import { Dialog, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from '@/components/ui/dialog';
import Label from '@/components/ui/label/Label.vue';
import { TooltipProvider } from '@/components/ui/tooltip';
import type { OptionParams, ProductSheet, Programmer } from '@/domain/product-sheet';
import type { Option } from '@/domain/shared/types';
import { monthLabel } from '@/lib/months';
import axios from 'axios';
import { computed, ref } from 'vue';
import EcommerceSizesDialog from './EcommerceSizesDialog.vue';

const props = defineProps<{
    destinations: OptionParams[];
    productSheets: ProductSheet[];
    months: Option[];
}>();

const { destinations, productSheets } = props;

const emits = defineEmits<{
    (event: 'programmerUpdated'): void;
}>();

const isDialogOpen = ref(false);
const dialogMode = ref<'edit' | 'view'>('edit');
const programmer = ref<Programmer>({
    id: 0,
    product_sheet_id: null,
    ecommerce_units: null,
} as Programmer);
const isLoading = ref(false);
const errorMessage = ref<string | null>(null);

const isReadOnly = computed(() => dialogMode.value === 'view');

/**
 * Determina si el registro fue auto-generado desde Sábana de Productos.
 * Usa el campo `is_auto_from_product_sheet` del backend (accessor serializado).
 */
function isAutoRow(row: Programmer): boolean {
    return row.is_auto_from_product_sheet === true;
}

const isAutoGenerated = computed(() => isAutoRow(programmer.value));
const isManual = computed(() => !isAutoRow(programmer.value));

const dialogTitle = computed(() => (isReadOnly.value ? 'Ver Lote Programado' : 'Editar Lote Programado'));
const dialogDescription = computed(() =>
    isReadOnly.value ? 'Aquí puedes ver los detalles del programador seleccionado.' : 'Aquí puedes editar los detalles del programador seleccionado.',
);

const destinationOptions = computed(() => destinations.map((destination) => ({ id: destination.id, name: destination.name })));

const programmerUnits = computed({
    get: () => programmer.value.units ?? '',
    set: (value: string | number) => {
        const parsed = Number(value);
        programmer.value.units = Number.isFinite(parsed) && parsed > 0 ? Math.floor(parsed) : null;
    },
});

function getProductSheetValue(sheet: ProductSheet): number {
    const candidate = (sheet as ProductSheet & { value?: number | string }).value ?? sheet.id;
    return Number(candidate);
}

function getProductSheetLabel(sheet: ProductSheet): string {
    const typedSheet = sheet as ProductSheet & { label?: string; display_reference?: string };
    return String(typedSheet.label ?? typedSheet.display_reference ?? sheet.reference ?? '').trim();
}

function getReferenceName(productSheetId: number | null): string {
    const productSheet = props.productSheets.find((sheet) => getProductSheetValue(sheet) === Number(productSheetId));
    return productSheet ? getProductSheetLabel(productSheet) : 'Referencia';
}

function initializeEcommerceSizes() {
    try {
        const ecommerceData = programmer.value.ecommerce_units;

        if (typeof ecommerceData === 'string') {
            programmer.value.ecommerce_units = JSON.parse(ecommerceData || '{}');
        } else if (ecommerceData && typeof ecommerceData === 'object') {
            programmer.value.ecommerce_units = ecommerceData;
        } else {
            programmer.value.ecommerce_units = {};
        }
    } catch {
        programmer.value.ecommerce_units = {};
    }
}

/**
 * Normaliza el valor de season para que matchee con el id del catálogo.
 * Soporta: número, string numérico, o texto de mes (ENERO, FEBRERO, etc).
 */
function normalizeSeasonValue(season: string | number | null | undefined): string | number | null {
    if (season === null || season === undefined || season === '') {
        return null;
    }

    // Si es número o string numérico válido, retornarlo como número
    const numericValue = Number(season);
    if (Number.isFinite(numericValue) && numericValue >= 1 && numericValue <= 12) {
        return numericValue;
    }

    // Si es texto de mes, buscar el id correspondiente en el catálogo
    if (typeof season === 'string') {
        const seasonUpper = season.toUpperCase().trim();
        const matchedOption = props.months?.find((m) => m.name.toUpperCase() === seasonUpper);
        if (matchedOption && typeof matchedOption.id !== 'boolean') {
            return matchedOption.id;
        }
    }

    // Fallback: retornar el valor original
    return season;
}

function openDialog(selectedProgrammer: Programmer, mode: 'edit' | 'view' = 'edit') {
    dialogMode.value = mode;
    programmer.value = { ...selectedProgrammer };
    // Normalizar season para que matchee con el catálogo
    programmer.value.season = normalizeSeasonValue(programmer.value.season) as string | null;
    initializeEcommerceSizes();
    isDialogOpen.value = true;
    errorMessage.value = null;
}

defineExpose({ openDialog });

function validateFields(): boolean {
    const requiredFields = [
        { field: programmer.value?.product_sheet_id, message: 'La referencia es obligatoria.' },
        { field: programmer.value?.season, message: 'La temporada es obligatoria.' },
        { field: programmer.value?.destination_id, message: 'El destino es obligatorio.' },
    ];

    for (const { field, message } of requiredFields) {
        if (!field) {
            errorMessage.value = message;
            return false;
        }
    }

    errorMessage.value = null;
    return true;
}

function resolveEcommerceValues(value?: string | Record<string, number> | null): Record<string, number> | null {
    if (!value) {
        return null;
    }

    if (typeof value === 'string') {
        try {
            const parsed = JSON.parse(value);
            if (parsed && typeof parsed === 'object') {
                return parsed as Record<string, number>;
            }
        } catch {
            return null;
        }
    }

    if (typeof value === 'object') {
        return value;
    }

    return null;
}

async function saveChanges() {
    if (!validateFields()) return;

    if (!programmer.value?.id) {
        errorMessage.value = 'No se encontró el ID del programador.';
        return;
    }

    isLoading.value = true;
    try {
        // Construir payload excluyendo campos según tipo
        const basePayload = {
            product_sheet_id: programmer.value.product_sheet_id,
            season: programmer.value.season,
            destination_id: programmer.value.destination_id,
            units: programmer.value.units,
            ecommerce_units:
                typeof programmer.value.ecommerce_units === 'string'
                    ? programmer.value.ecommerce_units
                    : JSON.stringify(programmer.value.ecommerce_units || {}),
        };

        let payload: Record<string, unknown>;

        if (isAutoGenerated.value) {
            // Auto-generados: incluir fecha entrega, NO incluir prioridad
            payload = {
                ...basePayload,
                estimated_delivery_date: programmer.value.estimated_delivery_date,
            };
        } else {
            // Manuales: incluir prioridad, NO incluir fecha entrega
            payload = {
                ...basePayload,
                priority: programmer.value.priority,
            };
        }

        await axios.put(`/comercial/programador/${programmer.value.id}`, payload);
        emits('programmerUpdated');
        isDialogOpen.value = false;
    } catch (error: unknown) {
        if (axios.isAxiosError(error)) {
            errorMessage.value = error.response?.data?.message || 'Hubo un error al actualizar el programador.';
        } else {
            errorMessage.value = 'Ocurrió un error inesperado.';
        }
    } finally {
        isLoading.value = false;
    }
}
</script>

<template>
    <Dialog v-model:open="isDialogOpen" aria-labelledby="dialog-title" aria-describedby="dialog-description">
        <FormDialogContent class="flex max-h-[95vh] max-w-[75vh] flex-col px-2 py-2">
            <TooltipProvider>
                <DialogHeader class="flex-shrink-0">
                    <DialogTitle>{{ dialogTitle }}</DialogTitle>
                    <DialogDescription>{{ dialogDescription }}</DialogDescription>
                </DialogHeader>
                <div class="flex-1 space-y-4 overflow-y-auto pr-2" style="scrollbar-width: thin">
                    <div v-if="errorMessage" class="text-sm text-red-500">
                        {{ errorMessage }}
                    </div>

                    <div class="flex flex-col gap-1">
                        <div class="flex items-center gap-2">
                            <Label class="text-sm font-medium">Referencia<span class="text-red-500">*</span></Label>
                            <HelpTooltip text="Sábana de producto asignada a este lote de producción." aria-label="Ayuda sobre referencia" />
                        </div>
                        <SelectField
                            id="reference"
                            v-model="programmer.product_sheet_id"
                            :options="
                                productSheets
                                    .map((sheet) => ({ id: getProductSheetValue(sheet), name: getProductSheetLabel(sheet) }))
                                    .filter((option) => option.name !== '')
                            "
                            label=""
                            required
                            :disabled="isReadOnly"
                            class="mt-1 w-full"
                        />
                    </div>

                    <div class="flex flex-col gap-1">
                        <div class="flex items-center gap-2">
                            <Label class="text-sm font-medium">Temporada<span class="text-red-500">*</span></Label>
                            <HelpTooltip text="Temporada o mes en el que se programará la producción del lote." aria-label="Ayuda sobre temporada" />
                        </div>
                        <!-- Auto-generados: mostrar como texto read-only -->
                        <template v-if="isAutoGenerated">
                            <div class="mt-1 rounded-md border border-input bg-muted/50 px-3 py-2 text-sm">
                                {{ monthLabel(programmer.season) }}
                            </div>
                        </template>
                        <!-- Manuales: mostrar como select editable -->
                        <template v-else>
                            <SelectField
                                id="season"
                                v-model="programmer.season"
                                :options="props.months"
                                label=""
                                required
                                :disabled="isReadOnly"
                                class="mt-1 w-full"
                            />
                        </template>
                    </div>

                    <!-- Prioridad: solo visible para lotes manuales -->
                    <div v-if="isManual" class="flex flex-col gap-1">
                        <div class="flex items-center gap-2">
                            <Label class="text-sm font-medium">Prioridad</Label>
                            <HelpTooltip text="Nivel de prioridad del lote de producción." aria-label="Ayuda sobre prioridad" />
                        </div>
                        <SelectField
                            id="priority"
                            v-model="programmer.priority"
                            :options="[
                                { id: 'A', name: 'A' },
                                { id: 'B', name: 'B' },
                                { id: 'C', name: 'C' },
                                { id: 'D', name: 'D' },
                            ]"
                            label=""
                            :disabled="isReadOnly"
                            class="mt-1 w-full"
                        />
                    </div>

                    <div class="flex flex-col gap-1">
                        <div class="flex items-center gap-2">
                            <Label class="text-sm font-medium">Destino<span class="text-red-500">*</span></Label>
                            <HelpTooltip text="Canal o mercado destino para el lote programado." aria-label="Ayuda sobre destino" />
                        </div>
                        <SelectField
                            id="destination"
                            v-model="programmer.destination_id"
                            :options="destinationOptions"
                            label=""
                            required
                            :disabled="isReadOnly"
                            class="mt-1 w-full"
                        />
                    </div>

                    <div class="flex flex-col gap-1">
                        <div class="flex items-center gap-2">
                            <Label class="text-sm font-medium">Unidades</Label>
                            <HelpTooltip
                                text="Cantidad total de unidades a programar. Si se deja vacío, queda pendiente."
                                aria-label="Ayuda sobre unidades"
                            />
                        </div>
                        <InputField type="number" v-model="programmerUnits" label="" placeholder="Unds. a programar" :disabled="isReadOnly" />
                    </div>

                    <!-- Fecha entrega estimada: solo visible para lotes auto-generados -->
                    <div v-if="isAutoGenerated" class="flex flex-col gap-1">
                        <div class="flex items-center gap-2">
                            <Label class="text-sm font-medium">Fecha entrega estimada</Label>
                            <HelpTooltip text="Fecha estimada de entrega de la muestra." aria-label="Ayuda sobre fecha entrega estimada" />
                        </div>
                        <InputField type="date" v-model="programmer.estimated_delivery_date!" label="" :disabled="isReadOnly" />
                    </div>

                    <div class="flex flex-col gap-1">
                        <div class="flex items-center gap-2">
                            <Label class="text-sm font-medium">E-commerce</Label>
                            <HelpTooltip
                                text="Distribución de unidades específica para ventas en línea por talla."
                                aria-label="Ayuda sobre e-commerce"
                            />
                        </div>
                        <EcommerceSizesDialog
                            :productSheet="{
                                sizes: productSheets.find((ps) => ps.id === programmer.product_sheet_id)?.sizes || '{}',
                                reference: getReferenceName(programmer.product_sheet_id),
                            }"
                            :existingValues="resolveEcommerceValues(programmer.ecommerce_units)"
                            :readonly="isReadOnly"
                            @sizesUpdated="
                                (data) => {
                                    if (!isReadOnly) {
                                        programmer.ecommerce_units = data.sizes;
                                    }
                                }
                            "
                        />
                    </div>
                </div>
            </TooltipProvider>

            <DialogFooter class="mt-4 flex flex-col gap-2 border-t pt-4 md:flex-row md:justify-end">
                <div class="w-full md:w-auto">
                    <button
                        type="button"
                        class="mx-auto flex w-full max-w-[140px] items-center justify-center gap-2 rounded-full border border-primary/40 bg-white px-5 py-2 text-sm font-semibold text-primary transition hover:bg-primary/10 focus:outline-none focus-visible:ring-2 focus-visible:ring-primary focus-visible:ring-offset-2"
                        @click="isDialogOpen = false"
                    >
                        {{ isReadOnly ? 'Cerrar' : 'Cancelar' }}
                    </button>
                </div>
                <div v-if="!isReadOnly" class="w-full md:w-auto">
                    <Button
                        type="button"
                        :class="[
                            'mx-auto flex w-full max-w-[140px] items-center justify-center rounded-full px-5 py-2 text-sm font-semibold shadow-sm',
                            isLoading ? 'cursor-not-allowed opacity-60' : '',
                        ]"
                        :disabled="isLoading"
                        @click="saveChanges"
                    >
                        {{ isLoading ? 'Guardando...' : 'Guardar' }}
                    </Button>
                </div>
            </DialogFooter>
        </FormDialogContent>
    </Dialog>
</template>
