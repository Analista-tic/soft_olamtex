import type { ProductSheet, Programmer } from '@/domain/product-sheet';
import { normalizeSizes } from '@/domain/product-sheet';
import { computed, ref } from 'vue';

export type EditableProgrammer = Omit<Programmer, 'season'> & { season: string | null };

export function useProgrammerForm() {
    const programmer = ref<EditableProgrammer>(createEmptyProgrammer());
    const isLoading = ref(false);

    function createEmptyProgrammer(): EditableProgrammer {
        return {
            id: 0,
            op_code: null,
            product_sheet_id: null,
            product_sheet: null,
            season: null,
            season_display: null,
            destination: null,
            destination_id: null,
            priority: null,
            isEcommerce: false,
            ecommerce_units: null,
            units: null,
            estimated_delivery_date: null,
            status: 'incomplete',
            source: undefined,
            is_auto_from_product_sheet: false,
            is_pending_completion: false,
            pending_fields: [],
            created_at: '',
            updated_at: '',
        };
    }

    function reset() {
        programmer.value = createEmptyProgrammer();
    }

    function fromProgrammer(
        source: Programmer,
        normalizeSeasonValue: (v: string | number | null | undefined) => string | null,
        normalizeIsoDate: (v: unknown) => string | null,
    ) {
        programmer.value = {
            ...createEmptyProgrammer(),
            ...source,
            season: normalizeSeasonValue(source.season),
            estimated_delivery_date: normalizeIsoDate(source.estimated_delivery_date),
        };
        initializeEcommerceSizes();
    }

    function initializeEcommerceSizes() {
        try {
            const data = programmer.value.ecommerce_units;
            if (typeof data === 'string') {
                programmer.value.ecommerce_units = JSON.parse(data || '{}');
            } else if (data && typeof data === 'object') {
                programmer.value.ecommerce_units = data;
            } else {
                programmer.value.ecommerce_units = {};
            }
        } catch {
            programmer.value.ecommerce_units = {};
        }
    }

    const isAutoGenerated = computed(() => programmer.value.is_auto_from_product_sheet === true);
    const isManual = computed(() => !isAutoGenerated.value);

    const programmerUnits = computed({
        get: () => programmer.value.units ?? '',
        set: (value: string | number) => {
            const parsed = Number(value);
            programmer.value.units = Number.isFinite(parsed) && parsed > 0 ? Math.floor(parsed) : null;
        },
    });

    function validateFields(setAlert: (msg: string, type?: string) => void): boolean {
        const requiredFields = [
            { field: programmer.value.product_sheet_id, message: 'La referencia es obligatoria.' },
            { field: programmer.value.season, message: 'La temporada es obligatoria.' },
            { field: programmer.value.destination_id, message: 'El destino es obligatorio.' },
        ];

        for (const { field, message } of requiredFields) {
            if (!field) {
                setAlert(message, 'warning');
                return false;
            }
        }

        return true;
    }

    function resolveEcommerceValues(value?: string | Record<string, number> | null): Record<string, number> | null {
        if (!value) return null;

        if (typeof value === 'string') {
            try {
                const parsed = JSON.parse(value);
                if (parsed && typeof parsed === 'object') return parsed as Record<string, number>;
            } catch {
                return null;
            }
        }

        if (typeof value === 'object') return value as Record<string, number>;
        return null;
    }

    function getProductSheetValue(sheet: ProductSheet): number {
        const candidate = (sheet as ProductSheet & { value?: number | string }).value ?? sheet.id;
        return Number(candidate);
    }

    function getProductSheetLabel(sheet: ProductSheet): string {
        const typed = sheet as ProductSheet & { label?: string; display_reference?: string };
        return String(typed.label ?? typed.display_reference ?? sheet.reference ?? '').trim();
    }

    function getDialogProductSheet(
        productSheets: ProductSheet[],
        productSheetId: number | null,
    ): { sizes: string | Record<string, boolean> | null; reference: string } {
        const ps = productSheets.find((s) => getProductSheetValue(s) === Number(productSheetId));
        return {
            sizes: normalizeSizes(ps?.sizes),
            reference: ps ? getProductSheetLabel(ps) : '',
        };
    }

    function parseUnitsInput(value: string | number | null | undefined): number | null {
        if (value === null || value === undefined) return null;
        const raw = typeof value === 'string' ? value.trim() : String(value);
        if (raw === '') return null;
        const numeric = Number(raw.replace(/[^0-9.]/g, ''));
        if (!Number.isFinite(numeric)) return null;
        const positive = Math.max(1, Math.floor(numeric));
        return Number.isFinite(positive) ? positive : null;
    }

    return {
        programmer,
        isLoading,
        isAutoGenerated,
        isManual,
        programmerUnits,
        createEmptyProgrammer,
        reset,
        fromProgrammer,
        initializeEcommerceSizes,
        validateFields,
        resolveEcommerceValues,
        getProductSheetValue,
        getProductSheetLabel,
        getDialogProductSheet,
        parseUnitsInput,
    };
}
