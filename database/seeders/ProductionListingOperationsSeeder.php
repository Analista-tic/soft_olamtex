    public function run(): void
    {
        // Crear secciones
        $sections = [
            'PREPARACION' => OperationSection::firstOrCreate(['name' => 'PREPARACION'], ['is_active' => true]),
            'ENSAMBLE' => OperationSection::firstOrCreate(['name' => 'ENSAMBLE'], ['is_active' => true]),
            'TERMINACION' => OperationSection::firstOrCreate(['name' => 'TERMINACION'], ['is_active' => true]),
        ];

        // Crear máquinas
        $machinesData = [
            'OFM' => 1.086,
            'MPP' => 1.16,
            'MF3H' => 1.145,
            'MF5H' => 1.145,
            'MULT' => 1.21,
            'FUSION' => 1.2,
            'BOTONAD' => 1.169,
            'OJALAD' => 1.169,
            'PRESIL' => 1.169,
            'TROQ' => 1.086,
            'PLANC' => 1.2,
            'COLL' => 1.19,
            'MP2A' => 1.18,
            'MF4H' => 1.145,
        ];

        $machines = [];
        foreach ($machinesData as $code => $factor) {
            $machines[$code] = Machine::firstOrCreate(['code' => $code], ['name' => "Máquina {$code}", 'supplement_factor' => $factor, 'is_active' => true]);
        }

        // Datos del CSV (formato simplificado)
        $now = now();
        $batch = [];
        $csvData = $this->getCsvData();
        $seenOperations = [];
        $insertedCount = 0;
        $skippedCount = 0;

        foreach ($csvData as $row) {
            [, $operation, $section, $machine, $samNeto] = $row;

            // Validar que la sección y máquina existan
            $sectionId = $sections[$section]->id ?? null;
            $machineId = $machines[$machine]->id ?? null;

            if (!$sectionId || !$machineId) {
                continue;
            }

            // Parsear acción y parte de prenda
            $parts = explode(' ', trim($operation), 2);
            $action = $parts[0];
            $garment = $parts[1] ?? '';

            // Crear clave única para detectar duplicados en los datos
            $uniqueKey = "{$action}|{$garment}";

            // Saltar si ya vimos esta operación en el archivo (dentro de memoria)
            if (isset($seenOperations[$uniqueKey])) {
                $skippedCount++;
                continue;
            }
            $seenOperations[$uniqueKey] = true;

            // Verificar si ya existe en la base de datos
            if (Operation::where('action', $action)->where('garment_part', $garment)->exists()) {
                $skippedCount++;
                continue;
            }

            $batch[] = [
                'action' => $action,
                'garment_part' => $garment,
                'section_id' => $sectionId,
                'machine_id_reference' => $machineId,
                'sam_base' => $samNeto,
                'is_active' => 1,
                'created_at' => $now,
                'updated_at' => $now,
            ];

            // Insertar en batches de 50
            if (count($batch) >= 50) {
                Operation::insert($batch);
                $insertedCount += count($batch);
                $batch = [];
            }
        }

        // Insertar resto
        if (!empty($batch)) {
            Operation::insert($batch);
            $insertedCount += count($batch);
        }

        $this->command->info("✓ Operaciones importadas: {$insertedCount}");
        $this->command->info("⊘ Operaciones omitidas (duplicadas): {$skippedCount}");
    }

